-- Create database tables

CREATE TABLE IF NOT EXISTS users (
  id TEXT NOT NULL UNIQUE PRIMARY KEY,
  family_id TEXT,

  username TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  role INTEGER NOT NULL DEFAULT 0,

  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,

  FOREIGN KEY(family_id) REFERENCES families(id) ON UPDATE CASCADE ON DELETE SET NULL
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS transactions (
  id TEXT NOT NULL UNIQUE PRIMARY KEY, 
  user_id TEXT NOT NULL,
  family_id TEXT,

  description TEXT NOT NULL DEFAULT 'Transaction',
  date TEXT NOT NULL DEFAULT '0000-00-00T00:00:00.000Z',
  credit_amount REAL NOT NULL DEFAULT 0.00,
  debit_amount REAL NOT NULL DEFAULT 0.00,
  merchant TEXT NOT NULL DEFAULT 'Merchant N/A',
  category TEXT NOT NULL DEFAULT 'Category N/A',
  payment_source TEXT NOT NULL DEFAULT 'Payment Source N/A',

  FOREIGN KEY(user_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL,
  FOREIGN KEY(family_id) REFERENCES families(id) ON UPDATE CASCADE ON DELETE SET NULL
) WITHOUT ROWID;

CREATE INDEX IDX_TRANSACTION_DATE ON transactions(date);

CREATE TABLE IF NOT EXISTS transaction_items (
  id TEXT NOT NULL UNIQUE PRIMARY KEY,
  transaction_id TEXT NOT NULL,

  description TEXT NOT NULL DEFAULT 'Transaction Item',
  amount REAL NOT NULL DEFAULT 0.00,
  category TEXT NOT NULL DEFAULT 'Category N/A',

  FOREIGN KEY(transaction_id) REFERENCES transactions(id) ON UPDATE CASCADE ON DELETE CASCADE
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS families (
  id TEXT NOT NULL UNIQUE PRIMARY KEY,
  admin_id TEXT NOT NULL,

  name TEXT NOT NULL,

  FOREIGN KEY(admin_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS refresh_tokens (
  id TEXT NOT NULL UNIQUE PRIMARY KEY,
  user_id TEXT NOT NULL,

  revoked INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT '0000-00-00T00:00:00.000Z',
  updated_at TEXT NOT NULL DEFAULT '0000-00-00T00:00:00.000Z',

  FOREIGN KEY(user_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE CASCADE
) WITHOUT ROWID;